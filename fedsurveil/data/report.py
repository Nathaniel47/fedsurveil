"""Write results/data_report.md: counts, class balance, site partitions, sample records, problems.

Run: python -m fedsurveil.data.report
"""

import hashlib

import numpy as np

from fedsurveil import config
from fedsurveil.data.load import ImageSet
from fedsurveil.data.partition import class_matrix, dirichlet_partition
from fedsurveil.data.prepare import DEFAULT_SITES, available_sets

OUT = config.RESULTS_DIR / "data_report.md"


def _hashes(x: np.ndarray) -> list[str]:
    return [hashlib.md5(img.tobytes()).hexdigest() for img in x]


def quality_checks(data: ImageSet) -> dict:
    train, val, test = _hashes(data.x_train), _hashes(data.x_val), _hashes(data.x_test)
    t = set(train)
    return {
        "duplicates_within_train": len(train) - len(t),
        "train_val_overlap": len(t & set(val)),
        "train_test_overlap": len(t & set(test)),
        "constant_images": int(sum(img.max() == img.min() for img in data.x_train)),
        "label_range_ok": bool(data.y_train.min() >= 0),
    }


def _counts(y: np.ndarray, k: int) -> list[int]:
    return np.bincount(y, minlength=k).tolist()


def dataset_section(data: ImageSet) -> list[str]:
    k = data.num_classes
    lines = [f"## {data.name}", ""]
    lines += ["| Split | Images | Shape | dtype |", "|---|---|---|---|"]
    for split in ("train", "val", "test"):
        x = getattr(data, f"x_{split}")
        lines.append(f"| {split} | {len(x)} | {x.shape[1:]} | {x.dtype} |")
    train_counts = _counts(data.y_train, k)
    ratio = max(train_counts) / max(1, min(train_counts))
    lines += ["", f"Classes: {k}. Train class counts: {train_counts}.", ""]
    lines.append(f"Imbalance (largest / smallest class in train): {ratio:.1f}x.")

    q = quality_checks(data)
    lines += ["", "Quality checks:", ""]
    lines += [f"- {key.replace('_', ' ')}: {value}" for key, value in q.items()]

    lines += ["", "Sample records (first 3 train items; pixel summary only):", ""]
    for i in range(min(3, len(data.x_train))):
        img = data.x_train[i]
        lines.append(
            f"- index {i}: label {int(data.y_train[i])}, shape {img.shape}, "
            f"pixel mean {img.mean():.1f}, min {img.min()}, max {img.max()}"
        )

    lines += [
        "",
        f"Site partitions ({DEFAULT_SITES} sites, seed 0):",
        "",
        "| alpha | smallest site | median site | largest site | classes per site (mean) "
        "| dominant class share (mean) |",
        "|---|---|---|---|---|---|",
    ]
    for alpha in config.DIRICHLET_ALPHAS:
        parts = dirichlet_partition(data.y_train, DEFAULT_SITES, alpha, seed=0)
        m = class_matrix(data.y_train, parts, k)
        sizes = m.sum(axis=1)
        present = (m > 0).sum(axis=1).mean()
        dominant = (m.max(axis=1) / sizes).mean()
        lines.append(
            f"| {alpha:g} | {sizes.min()} | {int(np.median(sizes))} | {sizes.max()} "
            f"| {present:.1f} | {dominant:.2f} |"
        )
    return lines + [""]


def problems(data: ImageSet) -> list[str]:
    found = []
    q = quality_checks(data)
    if q["duplicates_within_train"]:
        found.append(f"{data.name}: {q['duplicates_within_train']} duplicate train images")
    if q["train_test_overlap"]:
        found.append(f"{data.name}: {q['train_test_overlap']} train images also in test")
    if q["train_val_overlap"]:
        found.append(f"{data.name}: {q['train_val_overlap']} train images also in val")
    counts = _counts(data.y_train, data.num_classes)
    if max(counts) / max(1, min(counts)) > 5:
        found.append(f"{data.name}: class imbalance above 5x, so report macro-F1 as well")
    return found


def main() -> None:
    sets = available_sets()
    lines = ["# Data report", "", "Generated by `python -m fedsurveil.data.report`.", ""]
    all_problems: list[str] = []
    for data in sets:
        lines += dataset_section(data)
        all_problems += problems(data)
    lines += ["## Quality problems found", ""]
    lines += [f"- {p}" for p in all_problems] or ["- none found by the automatic checks"]
    names = {d.name for d in sets}
    if "ip102" not in names:
        lines += ["- IP102 is not included yet: it is a manual 3 GB download (see README)."]
    config.RESULTS_DIR.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
