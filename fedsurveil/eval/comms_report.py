"""Communication-cost analysis for low-bandwidth sites: write results/comms_report.md.

    python -m fedsurveil.eval.comms_report

Two parts: an analytic table of how many bytes one site uploads per round under each compression
scheme, and, for every logged run, how many rounds, megabytes and hours it takes to reach a target
accuracy on slow links.

The links are ILLUSTRATIVE assumptions, not measurements of any real network: sites train and
transfer in parallel, every transfer pays one fixed latency, and protocol overhead is ignored.
"""

import pandas as pd

from fedsurveil import config
from fedsurveil.eval.runs import Run, load_all, rounds_to_accuracy

LINKS_BPS = {"2G, 0.1 Mbit/s": 0.1e6, "3G, 1 Mbit/s": 1e6, "4G, 10 Mbit/s": 10e6}
LATENCY_S = 0.5
OUT = config.RESULTS_DIR / "comms_report.md"


def per_site_round_bytes(run: Run) -> tuple[float, float]:
    """(upload, download) bytes of one site in one round, from the logged totals."""
    n_sites = run.config.get("num_sites") or len(run.site_sizes or [1])
    sites = int(run.config.get("sites_per_round") or n_sites)
    first = run.rounds[0]
    return first.get("bytes_up", 0) / sites, first.get("bytes_down", 0) / sites


def seconds_per_round(run: Run, link_bps: float, latency_s: float = LATENCY_S) -> float:
    up, down = per_site_round_bytes(run)
    return (up + down) * 8 / link_bps + 2 * latency_s


def cost_to_target(run: Run, target: float) -> dict | None:
    """Rounds, total megabytes and per-link hours needed to first reach the target accuracy."""
    reached = rounds_to_accuracy(run, target)
    if reached is None:
        return None
    mb = sum(
        (r.get("bytes_up", 0) + r.get("bytes_down", 0)) / 1e6
        for r in run.rounds
        if r["round"] <= reached
    )
    out = {"rounds": reached, "total MB": mb}
    for name, bps in LINKS_BPS.items():
        out[f"hours, {name}"] = reached * seconds_per_round(run, bps) / 3600
    return out


def target_table(runs: list[Run], target: float) -> pd.DataFrame:
    rows = []
    for r in runs:
        if not r.rounds or r.rounds[0].get("bytes_up", 0) == 0:
            continue  # the central baseline sends nothing, so it has no communication cost
        cost = cost_to_target(r, target)
        rows.append({"run": r.label, "dataset": r.dataset, **(cost or {"rounds": None})})
    return pd.DataFrame(rows)


def analytic_table(model_bytes: int) -> pd.DataFrame:
    """Upload per site per round for each scheme, from the sizes defined in comms/compress.py."""
    n = model_bytes // 4
    schemes = {
        "dense float32 (FedAvg, FedProx)": n * 4,
        "int8 quantization": n + 4,
        "top-k, keep 10%": round(n * 0.10) * 8,
        "top-k, keep 1%": round(n * 0.01) * 8,
        "SCAFFOLD (dense, update + control variate)": 2 * n * 4,
    }
    rows = []
    for name, up in schemes.items():
        row = {
            "scheme": name,
            "upload bytes per round": up,
            "times smaller than dense": model_bytes / up,
        }
        for link, bps in LINKS_BPS.items():
            row[f"upload seconds, {link}"] = up * 8 / bps
        rows.append(row)
    return pd.DataFrame(rows)


def _cell(value) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "never reached"
    if isinstance(value, float):
        return f"{value:.3g}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def _md(df: pd.DataFrame) -> str:
    if df.empty:
        return "_no rows_"
    head = "| " + " | ".join(df.columns) + " |"
    rule = "|" + "---|" * len(df.columns)
    body = ["| " + " | ".join(_cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, rule, *body])


def build_report(runs: list[Run], targets=(0.8, 0.85)) -> str:
    model_bytes = next((r.model_bytes for r in runs if r.model_bytes), None)
    lines = [
        "# Communication-cost report",
        "",
        "Generated by `python -m fedsurveil.eval.comms_report`. Link speeds are illustrative "
        f"assumptions (sites work in parallel, {LATENCY_S} s latency per transfer, no protocol "
        "overhead), not measurements of a real network.",
        "",
    ]
    if model_bytes:
        lines += [
            f"## Bytes one site uploads per round (model: {model_bytes:,} bytes, from the logs)",
            "",
            _md(analytic_table(model_bytes)),
            "",
            "These sizes are exact for the code in `comms/compress.py`. Smaller uploads cost "
            "accuracy or extra rounds, and that effect has to be measured on a GPU: "
            "see notebooks/04_compression.ipynb. No compressed run has been logged yet.",
            "",
        ]
    for target in targets:
        lines += [f"## Cost to reach {target:.0%} accuracy", ""]
        lines += [_md(target_table(runs, target)), ""]
        lines += ["A missing row or empty 'rounds' means the run never reached the target.", ""]
    return "\n".join(lines)


def main() -> None:
    runs = load_all(config.RUNS_DIR, config.RESULTS_DIR)
    config.RESULTS_DIR.mkdir(exist_ok=True)
    OUT.write_text(build_report(runs), encoding="utf-8")
    print(f"wrote {OUT} from {len(runs)} runs")


if __name__ == "__main__":
    main()
